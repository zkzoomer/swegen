test('supported upload recovery certifies the same nonzero-exit capture without rewriting its exit code',async t=>{
 const finish='m=json.loads((j/"session.json").read_text()); m["pending_snapshot"]={"path":"waiting"}; m["uploaded_digest"]=None; (j/"session.json").write_text(json.dumps(m)); raise SystemExit(5)'
 const {root,terminal}=await setup(t,true,finish)
 terminal.exit();const failed=await poll(terminal,s=>!s.running)
 assert.equal(failed.exitCode,5);assert.equal(failed.traceSaved,false);assert.equal(await terminal.confirmed(),false)
 const journal=path.join(root,'journals/fixture'),metadata=path.join(journal,'session.json')
 const receipt=JSON.parse(await fs.readFile(metadata,'utf8'))
 receipt.pending_snapshot=null
 receipt.uploaded_digest=require('node:crypto').createHash('sha256').update(await fs.readFile(path.join(journal,'events.jsonl'))).digest('hex')
 await fs.writeFile(metadata,JSON.stringify(receipt))
 const recovered=await poll(terminal,s=>s.traceSaved)
 assert.equal(recovered.exitCode,5);assert.equal(recovered.traceSaved,true);assert.equal(await terminal.confirmed(),true)
 assert.equal(recovered.journal,journal)
})
