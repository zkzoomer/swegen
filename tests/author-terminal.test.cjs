async function poll(terminal,predicate){
 for(let i=0;i<150;i++){const state=await terminal.read();if(predicate(state))return state;await new Promise(r=>setTimeout(r,20))}
 throw new Error('PTY fixture timed out: '+JSON.stringify(await terminal.read()))
}
async function setup(t,withJournal=true,finish='print("\\r\\nDisconnected from this task. Any running work continues.\\r\\n",flush=True)'){
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'swegen-pty-')); t.after(()=>fs.rm(root,{recursive:true,force:true}))
 const fake=path.join(root,'fixture.py'),journals=path.join(root,'journals')
 const capture=withJournal?`j=pathlib.Path(${JSON.stringify(path.join(journals,'fixture'))}); j.mkdir(parents=True,exist_ok=True); data=((j/'events.jsonl').read_bytes() if (j/'events.jsonl').exists() else b'')+(json.dumps({'helix_event':'capture_started','session_id':'fixture-session','recorded_at':int(time.time())})+'\\n'+json.dumps({'helix_event':'capture_ended','complete':True,'recorded_at':int(time.time())})+'\\n').encode(); (j/'events.jsonl').write_bytes(data); (j/'session.json').write_text(json.dumps({'id':'fixture-session','directory':os.getcwd(),'thread_id':'fixture-thread','pending_snapshot':None,'uploaded_digest':hashlib.sha256(data).hexdigest()})); `:''
 await fs.writeFile(fake,`import os,tty,pathlib,json,hashlib,time\ntty.setraw(0)\nprint('\\x1b[2J\\x1b[HREADY\\r\\n>_ OpenAI Codex (fixture)\\r\\n› Ask Codex to do anything',flush=True)\npending=b''\nwhile True:\n pending+=os.read(0,65536)\n if b'\\r' not in pending:continue\n line,pending=pending.split(b'\\r',1)\n text=line.replace(b'\\x1b[200~',b'').replace(b'\\x1b[201~',b'').decode()\n if '/quit' in text:\n  ${capture}${finish}\n  break\n print('\\r\\nRECEIVED '+text.replace('\\n',' / ')+'\\r\\n',flush=True)\n`)
 const terminal=new AuthorTerminal(path.resolve(__dirname,'../scripts/author_pty.py'),root,path.join(root,'logs'),String,[journals])
 t.after(()=>terminal.stop());await terminal.start(['python3',fake]);await poll(terminal,s=>s.screen.includes('READY'))
 return {root,terminal,fake}
}
test('real PTY supports multiline messages, rendered screen, clean exit and save confirmation',async t=>{
 const {terminal}=await setup(t)
 terminal.send('Build the task.\nKeep selected values: $0; `literal`.')
 const state=await poll(terminal,s=>s.screen.includes('RECEIVED'))
 assert.match(state.screen,/Keep selected values: \$0; `literal`/)
 terminal.exit()
 const closed=await poll(terminal,s=>!s.running)
 assert.equal(closed.exitCode,0);assert.match(closed.screen,/Disconnected from this task/);assert.equal(closed.traceSaved,true);assert.equal(await terminal.confirmed(),true)
 const messages=await fs.readFile(path.join(path.dirname(state.log),'messages.jsonl'),'utf8')
 assert.match(messages,/Build the task/)
 const transport=await fs.readFile(state.log,'utf8')
 assert.match(transport,/traceSaved: true/)
 assert.doesNotMatch(transport,/\x1b|RECEIVED|Keep selected values/,'No raw TUI redraws or repeated message copies')
})
