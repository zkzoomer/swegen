test('oracle requires explicit full numeric reward, not a zero exit or model claim',()=>{
 assert.equal(fullOracleReward('{"ok":true,"data":{"reward":1}}'),true)
 assert.equal(fullOracleReward('{"data":{"reward":"1.0"}}'),true)
 for(const value of ['all tests pass','{"ok":true}','{"reward":0.5}','{"reward":1}\n{"reward":0}','{"agent_message":"reward=1"}','{"trials":[{"reward":1},{"reward":0}]}']) assert.equal(fullOracleReward(value),false,value)
})
