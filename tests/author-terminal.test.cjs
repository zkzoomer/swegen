test('queued launch rejects input and can be cancelled without poisoning a later real author segment',async t=>{
 const {root,terminal,fake}=await setup(t)
 terminal.exit();await poll(terminal,s=>!s.running&&s.traceSaved)
 const queued=path.join(root,'queued.py')
 await fs.writeFile(queued,`import os,json,time\nos.write(int(os.environ['SWEGEN_AUTHOR_STATUS_FD']),json.dumps({'type':'helix_queued'}).encode()+b'\\n')\nprint('waiting in queue',flush=True)\ntime.sleep(30)\n`)
 await terminal.start(['python3',queued]);const waiting=await poll(terminal,s=>s.phase==='queued')
 assert.equal(waiting.ready,false);assert.equal(waiting.launchStarted,false)
 assert.throws(()=>terminal.send('Do not lose this request.'),/wait for ready=true/)
 assert.throws(()=>terminal.key('enter'),/not connected/)
 terminal.exit();const cancelled=await poll(terminal,s=>!s.running)
 assert.equal(cancelled.traceSaved,false);assert.equal(cancelled.launchStarted,false)
 assert.match(cancelled.traceError,/no authoring trace was created/)
 await terminal.start(['python3',fake]);await poll(terminal,s=>s.ready)
 terminal.send('Real request after reconnect.')
 await poll(terminal,s=>s.screen.includes('RECEIVED'))
 terminal.exit();await poll(terminal,s=>!s.running&&s.traceSaved)
 assert.equal(await terminal.confirmed(),true)
 const messages=await fs.readFile(path.join(root,'logs/inner-2/messages.jsonl'),'utf8').catch(e=>e.code==='ENOENT'?'':Promise.reject(e))
 assert.equal(messages,'','Rejected queued text must not enter the input log or PTY')
})
